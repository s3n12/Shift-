-- Shift — Complete Supabase PostgreSQL Schema & Row-Level Security Policies
-- Run this script once in your Supabase Dashboard → SQL Editor.

-- 1. Profiles table (1-to-1 with Supabase auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  phone text,
  display_name text,
  auth_provider text not null default 'supabase',
  seeded boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Tasks table (Work Mode & Weekend Mode priorities)
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 200),
  is_completed boolean not null default false,
  mode text not null default 'work' check (mode in ('work', 'weekend')),
  notes text check (notes is null or char_length(notes) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists tasks_user_created_idx
  on public.tasks (user_id, created_at desc);

-- 3. Habits table (Weekend & daily mindful rituals)
create table if not exists public.habits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  title text not null check (char_length(trim(title)) between 1 and 160),
  category text not null default 'wellness' check (category in ('wellness', 'plants', 'mindful')),
  streak_count integer not null default 0 check (streak_count >= 0),
  completed_today boolean not null default false,
  last_completed_date text,
  target_minutes integer check (target_minutes is null or (target_minutes >= 1 and target_minutes <= 600)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists habits_user_created_idx
  on public.habits (user_id, created_at desc);

-- 4. Trips table (Upcoming getaways & packing checklists)
create table if not exists public.trips (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  destination text not null check (char_length(trim(destination)) between 1 and 140),
  subtitle text check (subtitle is null or char_length(subtitle) <= 240),
  travel_date text not null check (travel_date ~ '^\d{4}-\d{2}-\d{2}$'),
  cover_key text not null default 'kyoto' check (cover_key in ('kyoto', 'amalfi', 'alpine')),
  packing_list jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists trips_user_travel_date_idx
  on public.trips (user_id, travel_date asc);

-- 5. Strict Row-Level Security (users can ONLY access their own rows)
alter table public.profiles enable row level security;
alter table public.tasks enable row level security;
alter table public.habits enable row level security;
alter table public.trips enable row level security;

-- Profiles policies
drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
  on public.profiles for select
  using (auth.uid() = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own"
  on public.profiles for insert
  with check (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

drop policy if exists "profiles_delete_own" on public.profiles;
create policy "profiles_delete_own"
  on public.profiles for delete
  using (auth.uid() = id);

